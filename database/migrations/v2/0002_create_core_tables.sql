BEGIN;
CREATE TABLE core.products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL, description TEXT,
 is_active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE core.users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(100) NOT NULL UNIQUE, name VARCHAR(255) NOT NULL, email VARCHAR(255) UNIQUE,
 password_hash TEXT NOT NULL, is_active BOOLEAN NOT NULL DEFAULT TRUE, last_login_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE core.roles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE,
 description TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE core.permissions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code VARCHAR(150) NOT NULL UNIQUE,
 name VARCHAR(150) NOT NULL, description TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE core.user_roles (
 user_id BIGINT NOT NULL REFERENCES core.users(id) ON DELETE CASCADE,
 role_id BIGINT NOT NULL REFERENCES core.roles(id) ON DELETE CASCADE, PRIMARY KEY(user_id, role_id)
);
CREATE TABLE core.role_permissions (
 role_id BIGINT NOT NULL REFERENCES core.roles(id) ON DELETE CASCADE,
 permission_id BIGINT NOT NULL REFERENCES core.permissions(id) ON DELETE CASCADE, PRIMARY KEY(role_id, permission_id)
);
CREATE TABLE core.customers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_number VARCHAR(100), name VARCHAR(255) NOT NULL,
 address_line_1 VARCHAR(255), address_line_2 VARCHAR(255), address_line_3 VARCHAR(255), city VARCHAR(100),
 province VARCHAR(100), postal_code VARCHAR(20), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_customers_customer_number ON core.customers(customer_number) WHERE customer_number IS NOT NULL;
CREATE TABLE core.customer_accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id BIGINT NOT NULL REFERENCES core.customers(id),
 product_id BIGINT NOT NULL REFERENCES core.products(id), account_number VARCHAR(100) NOT NULL, account_name VARCHAR(255),
 is_active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(product_id, account_number)
);
CREATE TABLE core.customer_contacts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id BIGINT NOT NULL REFERENCES core.customers(id) ON DELETE CASCADE,
 type VARCHAR(20) NOT NULL CHECK(type IN ('email','phone')), value VARCHAR(255) NOT NULL,
 is_primary BOOLEAN NOT NULL DEFAULT FALSE, is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(customer_id, type, value)
);
CREATE TABLE core.attachments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id BIGINT REFERENCES core.products(id),
 name VARCHAR(255) NOT NULL, file_name VARCHAR(255) NOT NULL, storage_key TEXT NOT NULL, mime_type VARCHAR(100),
 size_bytes BIGINT CHECK(size_bytes IS NULL OR size_bytes >= 0), checksum VARCHAR(128), is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_by BIGINT REFERENCES core.users(id), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE core.settings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, key VARCHAR(150) NOT NULL UNIQUE, value JSONB NOT NULL DEFAULT '{}'::jsonb,
 description TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE core.audit_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT REFERENCES core.users(id) ON DELETE SET NULL,
 action VARCHAR(100) NOT NULL, entity_type VARCHAR(150), entity_id VARCHAR(100), metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
 ip_address INET, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMIT;
